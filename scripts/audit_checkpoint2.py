"""저장된 실제 증거 재검사·자격 노출 검사·서비스 종료 확인. 파이프라인은 변경하지 않습니다."""
import hashlib
import json
import subprocess
from datetime import datetime, timezone
from pathlib import Path

from dataops_copilot.artifact_store import ArtifactStore
from dataops_copilot.models import Report
from dataops_copilot.recovery import check_recovery

ROOT = Path(__file__).resolve().parents[1]
RECORDS = ROOT / "artifacts" / "checkpoint2"
RUNTIME = ROOT.parents[1] / "work" / "runtime"


def main():
    e2e = json.loads((RECORDS / "live-e2e.json").read_text())
    limits = json.loads((RECORDS / "live-limits.json").read_text())
    negative = json.loads((RECORDS / "post-recovery-negatives.json").read_text())
    assert e2e["success"] and len(e2e["runs"]) == 7 and len(e2e["recoveries"]) == 3
    assert limits["success"] and negative["success"]
    reports = {name: Report.model_validate_json((RECORDS / f"{name}-report.json").read_text())
               for name in ("normal", "schema", "quality", "connection", "schema-followup", "quality-followup", "connection-followup")}
    rechecked = []
    for case in ("schema", "quality", "connection"):
        original, followup = reports[case], reports[case + "-followup"]
        context = next(e for e in followup.evidence if e.kind == "get_task_context")
        artifacts = next(e for e in followup.evidence if e.kind == "get_dbt_artifacts")
        check = check_recovery(original.incident_ref, followup.incident_ref, context, artifacts)
        assert check.recovered
        rechecked.append(check.model_dump())
    store = ArtifactStore(RECORDS / "dbt-archives")
    for report in reports.values():
        preserved = store.load(report.incident_ref)
        reported = next(e.data for e in report.evidence if e.kind == "get_dbt_artifacts")
        assert preserved["content_hashes"] == reported["content_hashes"]
        assert preserved["invocation_id"] == reported["invocation_id"]
    containers = []
    for name in ("dataops-c-cp2-airflow", "dataops-c-cp2-postgres"):
        info = json.loads(subprocess.check_output(["docker", "inspect", name], text=True))[0]
        item = {"name": name, "running": info["State"]["Running"], "status": info["State"]["Status"]}
        containers.append(item)
        assert not item["running"]
    processes = subprocess.check_output(["ps", "-axo", "pid,command"], text=True)
    mcp_servers = [line for line in processes.splitlines() if " -m dataops_copilot.mcp_server " in line]
    assert not mcp_servers
    generated = json.loads((RUNTIME / "generated-credentials.json").read_text())
    leaks = []
    for path in ROOT.parent.rglob("*"):
        if path.is_file() and ".venv" not in path.parts and "__pycache__" not in path.parts:
            try:
                value = path.read_text()
            except (OSError, UnicodeError):
                continue
            if any(secret in value for secret in generated.values()):
                leaks.append(str(path.relative_to(ROOT.parent)))
    assert not leaks
    source_hashes = {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest()
        for folder in ("src", "pipeline", "scripts", "tests", "deployment", "docs") for p in (ROOT / folder).rglob("*")
        if p.is_file() and "__pycache__" not in p.parts}
    for name in ("README.md", "pyproject.toml", "uv.lock"):
        source_hashes[name] = hashlib.sha256((ROOT / name).read_bytes()).hexdigest()
    (RECORDS / "source-manifest.json").write_text(json.dumps(source_hashes, indent=2))
    references = Path("/Users/lim/Documents/Codex/2026-10-20/1-dataops-observability-copilot-de-apache/outputs/dataops-docs")
    output = {"success": True, "audited_at": datetime.now(timezone.utc).isoformat(),
        "archived_actual_evidence_rechecked": rechecked, "artifact_pairs_verified": len(reports),
        "containers": containers, "remaining_mcp_servers": mcp_servers, "credential_leak_files": leaks,
        "credential_scan_scope": "only values generated by this session; outputs only",
        "original_readonly_reference_sha256": {name: hashlib.sha256((references / name).read_bytes()).hexdigest() for name in ("PDR.md", "ADR.md")}}
    (RECORDS / "final-audit.json").write_text(json.dumps(output, ensure_ascii=False, indent=2))
    print(json.dumps({"success": True, "artifact_pairs_verified": len(reports), "recovery_rechecks": len(rechecked), "containers_stopped": True, "mcp_servers": 0, "credential_leaks": 0}))


if __name__ == "__main__":
    main()
